# Install the Tether client plugin into the DeepSeek Harness desktop profile.
# The plugin is plain ESM; there is no build step.
param(
  [switch]$Restart,
  [switch]$VerifyPackage
)
$ErrorActionPreference = "Stop"

$AppDir = Split-Path -Parent $PSScriptRoot
$Plugin = Join-Path $AppDir "packages\dsh-plugin-tether"
$SurfacePackage = Join-Path $AppDir "packages\tether-dsh-surface"
$UpdaterRoot = [IO.Path]::GetFullPath((Join-Path $SurfacePackage "updater"))
$UpdaterTarget = [IO.Path]::GetFullPath((Join-Path $UpdaterRoot "tether"))
$UpdaterPrefix = $UpdaterRoot.TrimEnd([IO.Path]::DirectorySeparatorChar, [IO.Path]::AltDirectorySeparatorChar) + [IO.Path]::DirectorySeparatorChar
if (-not $UpdaterTarget.StartsWith($UpdaterPrefix, [StringComparison]::OrdinalIgnoreCase)) {
  throw "Plugin updater destination is outside the surface package."
}
$UpdaterFiles = @(
  "__init__.py",
  "updates.py",
  "updates_cli.py",
  "node\__init__.py",
  "node\dsh_sessions.py"
)
$UpdaterComplete = @($UpdaterFiles | Where-Object { -not (Test-Path (Join-Path $UpdaterTarget $_)) }).Count -eq 0
if (-not $UpdaterComplete) {
  $UpdaterSource = Join-Path $AppDir "tether"
  if (-not (Test-Path (Join-Path $UpdaterSource "updates.py"))) {
    throw "Plugin updater runtime is incomplete and source files are unavailable. Reinstall a complete Tether plugin package."
  }
  foreach ($directory in @($SurfacePackage, $UpdaterRoot, $UpdaterTarget)) {
    if (Test-Path $directory) {
      $item = Get-Item -LiteralPath $directory -Force
      if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) {
        throw "Plugin updater destination cannot pass through a symbolic link or junction."
      }
    }
  }
  New-Item -ItemType Directory -Path $UpdaterTarget -Force | Out-Null
  foreach ($relative in $UpdaterFiles) {
    $source = Join-Path $UpdaterSource $relative
    if (-not (Test-Path $source)) { throw "Plugin updater source file is missing: $relative" }
    if ((Get-Item -LiteralPath $source -Force).Attributes -band [IO.FileAttributes]::ReparsePoint) {
      throw "Plugin updater source cannot be a symbolic link: $relative"
    }
    $destination = Join-Path $UpdaterTarget $relative
    New-Item -ItemType Directory -Path (Split-Path -Parent $destination) -Force | Out-Null
    Copy-Item -LiteralPath $source -Destination $destination -Force
  }
}
if (@($UpdaterFiles | Where-Object { -not (Test-Path (Join-Path $UpdaterTarget $_)) }).Count -gt 0) {
  throw "Plugin updater runtime verification failed."
}
foreach ($directory in @($SurfacePackage, $UpdaterRoot, $UpdaterTarget)) {
  if (Test-Path $directory) {
    $item = Get-Item -LiteralPath $directory -Force
    if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) {
      throw "Plugin updater destination cannot pass through a symbolic link or junction."
    }
  }
}
foreach ($relative in $UpdaterFiles) {
  $item = Get-Item -LiteralPath (Join-Path $UpdaterTarget $relative) -Force
  if ($item.PSIsContainer -or $item.Attributes -band [IO.FileAttributes]::ReparsePoint) {
    throw "Plugin updater runtime contains an unsafe file: $relative"
  }
}
$NativeUiBuild = Join-Path $AppDir "scripts\build-native-ui-bridge.mjs"
$NativeUiSourceRoot = Join-Path $AppDir ".runtime\npm\node_modules\@deepseek-ai"
$NativeUiSources = @(
  "dsh-client-ui-chat\lib\client.js",
  "dsh-client-ui-chat\package.json",
  "dsh-client-ui-workspace\lib\client.js",
  "dsh-client-ui-workspace\package.json",
  "dsh-client-ui-sidebar-files\lib\client.js",
  "dsh-client-ui-sidebar-files\package.json",
  "dsh-client-ui-tool\lib\client.js",
  "dsh-client-ui-tool\package.json",
  "dsh-client-ui-conversation\lib\client.js",
  "dsh-client-ui-conversation\package.json"
)
$CanBuildNativeUi = (Test-Path $NativeUiBuild) -and @($NativeUiSources | Where-Object {
  -not (Test-Path (Join-Path $NativeUiSourceRoot $_))
}).Count -eq 0
$NativeUiClient = Join-Path $AppDir "packages\tether-dsh-native-ui\lib\client.js"
if ($CanBuildNativeUi) {
  Push-Location $AppDir
  try {
    & node $NativeUiBuild
    if ($LASTEXITCODE -ne 0) { throw "Native DSH UI bridge generation failed with exit code $LASTEXITCODE" }
  } finally {
    Pop-Location
  }
} else {
  if (-not (Test-Path $NativeUiClient)) {
    throw "Native DSH UI bridge sources and prebuilt client are both unavailable."
  }
  $NativeUiHeader = Get-Content -LiteralPath $NativeUiClient -TotalCount 8 | Out-String
  if ($NativeUiHeader -notmatch "Generated by scripts/build-native-ui-bridge\.mjs" -or
      $NativeUiHeader -notmatch "@deepseek-ai/dsh-client-ui-chat .*sha256:" -or
      $NativeUiHeader -notmatch "@deepseek-ai/dsh-client-ui-conversation .*sha256:") {
    throw "Prebuilt Native DSH UI bridge is missing its generated source integrity header."
  }
  Write-Host "[tether] Using the verified prebuilt Native DSH UI bridge."
}
if ($VerifyPackage) {
  if (-not (Test-Path (Join-Path $Plugin "package.json"))) {
    throw "Plugin package not found at $Plugin"
  }
  Write-Host "[tether] Offline package verification passed."
  exit 0
}
if (-not (Test-Path (Join-Path $Plugin "package.json"))) {
  throw "Plugin package not found at $Plugin"
}

$DshHome = if ($env:DSH_HOME) { $env:DSH_HOME } else { Join-Path $HOME ".dsh" }
$ProfileDir = Join-Path $DshHome "profiles\desktop"
$ProfilePkg = Join-Path $ProfileDir "package.json"
if (-not (Test-Path $ProfilePkg)) {
  throw "Desktop profile not found at $ProfilePkg. Launch DeepSeek Harness once, then rerun."
}

$candidates = @(
  $env:DSH_CLI,
  "D:\DeepSeek harness\resources\runtime\cli\bin\dsh.cmd",
  (Join-Path $env:LOCALAPPDATA "Programs\DeepSeek Harness\resources\runtime\cli\bin\dsh.cmd")
) | Where-Object { $_ -and (Test-Path $_) }
if (-not $candidates) {
  throw "dsh CLI not found. Set DSH_CLI to resources\runtime\cli\bin\dsh.cmd."
}
$Dsh = @($candidates)[0]

$backup = "$ProfilePkg.bak-tether-plugin-" + (Get-Date -Format "yyyyMMdd-HHmmss")
Copy-Item -LiteralPath $ProfilePkg -Destination $backup
Write-Host "[tether] profile backup: $backup"

$env:DSH_HOME = $DshHome
# Remove first so pnpm refreshes hard-linked client files when the source changed.
& $Dsh plugin --profile desktop remove tether-dsh-plugin | Out-Null
& $Dsh plugin --profile desktop add "file:$Plugin"
if ($LASTEXITCODE -ne 0) { throw "dsh plugin add failed with exit code $LASTEXITCODE" }

Write-Host "[tether] plugin installed. Restart DeepSeek Harness to load it."
Write-Host "[tether] The sidebar entry is named Tether."
if ($Restart) {
  $exe = "D:\DeepSeek harness\DeepSeek Harness.exe"
  if (-not (Test-Path $exe)) { throw "Set the DeepSeek Harness path in install-plugin.ps1 (-Restart)." }
  Get-Process "DeepSeek Harness" -ErrorAction SilentlyContinue | Stop-Process -Force
  Start-Sleep -Seconds 2
  Remove-Item Env:ELECTRON_RUN_AS_NODE -ErrorAction SilentlyContinue
  Start-Process $exe
  Write-Host "[tether] DeepSeek Harness restarted."
}
